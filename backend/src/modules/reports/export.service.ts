import ExcelJS from "exceljs";

export interface ExportColumn {
  header: string;
  key: string;
  width?: number;
  format?: "currency" | "date" | "number" | "text";
}

export interface ExportMetadata {
  title: string;
  companyContext: string;
  generatedBy: string;
  generatedAt: string;
  filtersApplied: Record<string, any>;
  summaryMetrics?: Record<string, string | number>;
}

export class ExportService {
  /**
   * Generates standard RFC 4180 compliant CSV string with UTF-8 BOM.
   * Includes metadata banner block at top for enterprise compliance.
   */
  public generateCsv(columns: ExportColumn[], rows: Record<string, any>[], meta: ExportMetadata): string {
    const lines: string[] = [];

    // 1. Compliance Header Metadata Banner
    lines.push(`"Report Title","${this.escapeCsv(meta.title)}"`);
    lines.push(`"Company Context","${this.escapeCsv(meta.companyContext)}"`);
    lines.push(`"Generated By","${this.escapeCsv(meta.generatedBy)}"`);
    lines.push(`"Generated At","${this.escapeCsv(meta.generatedAt)}"`);

    // Filters line
    const filterParts = Object.entries(meta.filtersApplied)
      .filter(([_, v]) => v !== undefined && v !== null && v !== "")
      .map(([k, v]) => `${k}=${v}`)
      .join("; ");
    lines.push(`"Filters Applied","${this.escapeCsv(filterParts || "None (Full Dataset)")}"`);

    // Summary Metrics (if provided)
    if (meta.summaryMetrics) {
      const summaryParts = Object.entries(meta.summaryMetrics)
        .map(([k, v]) => `${k}: ${v}`)
        .join(" | ");
      lines.push(`"Summary Metrics","${this.escapeCsv(summaryParts)}"`);
    }

    lines.push(""); // Empty separator line

    // 2. Column Headers
    const headers = columns.map((col) => `"${this.escapeCsv(col.header)}"`);
    lines.push(headers.join(","));

    // 3. Data Rows
    for (const row of rows) {
      const rowValues = columns.map((col) => {
        const val = row[col.key];
        if (val === undefined || val === null) {
          return '""';
        }
        if (col.format === "currency" && typeof val === "number") {
          return `"${val.toFixed(2)}"`;
        }
        if (val instanceof Date) {
          return `"${val.toISOString()}"`;
        }
        return `"${this.escapeCsv(String(val))}"`;
      });
      lines.push(rowValues.join(","));
    }

    // Prepend UTF-8 Byte Order Mark (BOM) for universal Excel compatibility
    return "\uFEFF" + lines.join("\r\n");
  }

  /**
   * Generates native OpenXML XLSX binary buffer with Pantone Enterprise branding.
   */
  public async generateXlsx(columns: ExportColumn[], rows: Record<string, any>[], meta: ExportMetadata): Promise<Buffer> {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = "Pantone Fixed Asset Management System";
    workbook.created = new Date();
    workbook.properties.date1904 = false;

    const worksheet = workbook.addWorksheet(meta.title.substring(0, 31));

    // 1. Pantone Header Branding Banner
    const titleRow = worksheet.addRow([meta.title.toUpperCase()]);
    titleRow.font = { bold: true, size: 14, color: { argb: "FFFFFFFF" } };
    titleRow.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF0D9488" }, // Pantone Teal #0d9488
    };

    worksheet.addRow(["Company Context:", meta.companyContext]);
    worksheet.addRow(["Generated By:", meta.generatedBy]);
    worksheet.addRow(["Generated At:", meta.generatedAt]);

    const filterParts = Object.entries(meta.filtersApplied)
      .filter(([_, v]) => v !== undefined && v !== null && v !== "")
      .map(([k, v]) => `${k}=${v}`)
      .join("; ");
    worksheet.addRow(["Filters Applied:", filterParts || "None (Full Dataset)"]);

    if (meta.summaryMetrics) {
      const summaryRow = worksheet.addRow([
        "Summary Totals:",
        Object.entries(meta.summaryMetrics).map(([k, v]) => `${k}: ${v}`).join(" | ")
      ]);
      summaryRow.font = { bold: true, color: { argb: "FF0F766E" } };
    }

    worksheet.addRow([]); // Blank line

    // 2. Table Header Row
    const headerRow = worksheet.addRow(columns.map((c) => c.header));
    headerRow.font = { bold: true, color: { argb: "FFFFFFFF" }, size: 10 };
    headerRow.alignment = { vertical: "middle", horizontal: "center" };
    headerRow.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF1E293B" }, // Slate 800
    };

    // 3. Data Rows
    for (const row of rows) {
      const rowData = columns.map((col) => {
        const val = row[col.key];
        if (val === undefined || val === null) return "";
        if (col.format === "currency" || col.format === "number") {
          return Number(val) || 0;
        }
        return val;
      });
      const dataRow = worksheet.addRow(rowData);
      dataRow.font = { size: 9 };

      // Apply cell formatting
      columns.forEach((col, idx) => {
        const cell = dataRow.getCell(idx + 1);
        if (col.format === "currency") {
          cell.numFmt = "$#,##0.00";
          cell.alignment = { horizontal: "right" };
        } else if (col.format === "number") {
          cell.numFmt = "#,##0";
          cell.alignment = { horizontal: "right" };
        } else if (col.format === "date") {
          cell.alignment = { horizontal: "center" };
        }
      });
    }

    // 4. Set Intelligent Column Widths
    columns.forEach((col, idx) => {
      const worksheetCol = worksheet.getColumn(idx + 1);
      let maxLen = col.header.length;
      for (const row of rows) {
        const val = row[col.key];
        if (val) {
          const str = String(val);
          if (str.length > maxLen) maxLen = str.length;
        }
      }
      worksheetCol.width = Math.min(45, Math.max(col.width || 12, maxLen + 3));
    });

    const buffer = await workbook.xlsx.writeBuffer();
    return Buffer.from(buffer);
  }

  private escapeCsv(val: string): string {
    return val.replace(/"/g, '""');
  }
}

export const exportService = new ExportService();
